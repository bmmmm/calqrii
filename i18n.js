// UI strings. Every key exists in both languages with the same type
// (test/model.test.mjs pins the parity). Functions take the values they format.

const RULE = {
  en: { daily: 'day', weekly: 'week', monthly: 'month', yearly: 'year' },
  de: { daily: 'Tag', weekly: 'Woche', monthly: 'Monat', yearly: 'Jahr' },
};
const RULE_PL = {
  en: { daily: 'days', weekly: 'weeks', monthly: 'months', yearly: 'years' },
  de: { daily: 'Tage', weekly: 'Wochen', monthly: 'Monate', yearly: 'Jahre' },
};

const EVERY_DE = { daily: 'Jeden Tag', weekly: 'Jede Woche', monthly: 'Jeden Monat', yearly: 'Jedes Jahr' };

const DUR_UNITS = { en: ['h', 'min'], de: ['Std.', 'Min.'] };

/** '1 h 15 min' / '1 Std. 15 Min.'; whole hours and sub-hour values drop the empty part. */
function durLabel(lang, min) {
  const [hu, mu] = DUR_UNITS[lang];
  const h = Math.floor(min / 60);
  const m = min % 60;
  return [h ? `${h} ${hu}` : '', m ? `${m} ${mu}` : ''].filter(Boolean).join(' ');
}

function recSummary(lang, rec, dayNames) {
  if (rec.freq === 'none') return '';
  const every = rec.interval === 1
    ? (lang === 'de' ? EVERY_DE[rec.freq] : `Every ${RULE.en[rec.freq]}`)
    : (lang === 'de' ? `Alle ${rec.interval} ${RULE_PL.de[rec.freq]}` : `Every ${rec.interval} ${RULE_PL.en[rec.freq]}`);
  const parts = [every];
  if (rec.freq === 'weekly' && rec.byDay.length) {
    parts.push((lang === 'de' ? 'am ' : 'on ') + rec.byDay.map((d) => dayNames[d] || d).join(', '));
  }
  if (rec.count !== null) parts.push(lang === 'de' ? `${rec.count}-mal` : `${rec.count} times`);
  if (rec.until !== null) parts.push((lang === 'de' ? 'bis ' : 'until ') + rec.until);
  return parts.join(', ');
}

